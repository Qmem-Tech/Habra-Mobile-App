CREATE OR REPLACE VIEW public.admin_subscription_current_v1 AS
SELECT
  p.id AS user_id,
  p.email,
  p.full_name,
  p.role,
  p.stripe_customer_id,
  p.owner_tools_subscription_active,
  p.owner_tools_subscription_tier,
  p.owner_tools_subscription_status,
  p.owner_tools_subscription_source,
  p.owner_tools_subscription_origin_id,
  p.owner_tools_subscription_updated_at
FROM public.profiles p;

ALTER VIEW public.admin_subscription_current_v1 SET (security_invoker = true);

CREATE OR REPLACE VIEW public.admin_billing_transactions_v1 AS
SELECT
  e.id::text AS ledger_id,
  e.created_at,
  e.user_id,
  p.email,
  p.full_name,
  e.stripe_customer_id,
  e.stripe_subscription_id,
  null::text AS stripe_invoice_id,
  'subscription'::text AS ledger_type,
  e.event_type,
  e.status,
  e.tier,
  null::bigint AS amount_cents,
  null::text AS currency
FROM public.billing_subscription_events e
LEFT JOIN public.profiles p ON p.id = e.user_id
UNION ALL
SELECT
  i.id::text AS ledger_id,
  i.created_at,
  i.user_id,
  p.email,
  p.full_name,
  i.stripe_customer_id,
  i.stripe_subscription_id,
  i.stripe_invoice_id,
  'invoice'::text AS ledger_type,
  i.event_type,
  COALESCE(i.status, 'unknown') AS status,
  COALESCE(p.owner_tools_subscription_tier, 'basic') AS tier,
  i.amount_cents,
  i.currency
FROM public.billing_invoice_events i
LEFT JOIN public.profiles p ON p.id = i.user_id;

ALTER VIEW public.admin_billing_transactions_v1 SET (security_invoker = true);

CREATE OR REPLACE FUNCTION public.admin_list_billing_transactions(
  p_from timestamptz DEFAULT NULL,
  p_to timestamptz DEFAULT NULL,
  p_tier text DEFAULT NULL,
  p_status text DEFAULT NULL,
  p_user_id uuid DEFAULT NULL,
  p_limit int DEFAULT 100,
  p_offset int DEFAULT 0
)
RETURNS TABLE (
  ledger_id text,
  created_at timestamptz,
  user_id uuid,
  email text,
  full_name text,
  stripe_customer_id text,
  stripe_subscription_id text,
  stripe_invoice_id text,
  ledger_type text,
  event_type text,
  status text,
  tier text,
  amount_cents bigint,
  currency text
)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    t.ledger_id,
    t.created_at,
    t.user_id,
    t.email,
    t.full_name,
    t.stripe_customer_id,
    t.stripe_subscription_id,
    t.stripe_invoice_id,
    t.ledger_type,
    t.event_type,
    t.status,
    t.tier,
    t.amount_cents,
    t.currency
  FROM public.admin_billing_transactions_v1 t
  WHERE
    (p_from IS NULL OR t.created_at >= p_from)
    AND (p_to IS NULL OR t.created_at <= p_to)
    AND (p_tier IS NULL OR lower(t.tier) = lower(p_tier))
    AND (p_status IS NULL OR lower(t.status) = lower(p_status))
    AND (p_user_id IS NULL OR t.user_id = p_user_id)
  ORDER BY t.created_at DESC
  LIMIT GREATEST(COALESCE(p_limit, 100), 1)
  OFFSET GREATEST(COALESCE(p_offset, 0), 0);
$$;

REVOKE ALL ON FUNCTION public.admin_list_billing_transactions(
  timestamptz,
  timestamptz,
  text,
  text,
  uuid,
  int,
  int
) FROM PUBLIC;

