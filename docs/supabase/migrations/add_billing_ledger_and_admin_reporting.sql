-- Stripe-first billing ledger and super-admin reporting surfaces.
-- Safe to run multiple times.

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS owner_tools_subscription_source text DEFAULT 'stripe',
  ADD COLUMN IF NOT EXISTS owner_tools_subscription_origin_id text;

COMMENT ON COLUMN public.profiles.owner_tools_subscription_source
  IS 'Canonical source that last updated owner tools subscription state (stripe or revenuecat). Stripe is authoritative.';
COMMENT ON COLUMN public.profiles.owner_tools_subscription_origin_id
  IS 'Source object id used for traceability (for Stripe this is the subscription id).';

CREATE OR REPLACE FUNCTION public.enforce_owner_tools_subscription_source_priority()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP <> 'UPDATE' THEN
    RETURN NEW;
  END IF;

  IF COALESCE(OLD.owner_tools_subscription_source, 'stripe') = 'stripe'
     AND COALESCE(NEW.owner_tools_subscription_source, 'stripe') <> 'stripe'
     AND COALESCE(NEW.owner_tools_subscription_updated_at, OLD.owner_tools_subscription_updated_at, timezone('utc', now()))
         <= COALESCE(OLD.owner_tools_subscription_updated_at, timezone('utc', now()))
  THEN
    NEW.owner_tools_subscription_active := OLD.owner_tools_subscription_active;
    NEW.owner_tools_subscription_tier := OLD.owner_tools_subscription_tier;
    NEW.owner_tools_subscription_status := OLD.owner_tools_subscription_status;
    NEW.owner_tools_subscription_source := OLD.owner_tools_subscription_source;
    NEW.owner_tools_subscription_origin_id := OLD.owner_tools_subscription_origin_id;
    NEW.owner_tools_subscription_updated_at := OLD.owner_tools_subscription_updated_at;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_enforce_owner_tools_subscription_source_priority ON public.profiles;
CREATE TRIGGER trg_enforce_owner_tools_subscription_source_priority
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.enforce_owner_tools_subscription_source_priority();

CREATE TABLE IF NOT EXISTS public.billing_subscription_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  stripe_event_id text NOT NULL,
  event_type text NOT NULL,
  user_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  stripe_customer_id text,
  stripe_subscription_id text,
  tier text NOT NULL DEFAULT 'basic',
  status text NOT NULL DEFAULT 'inactive',
  source text NOT NULL DEFAULT 'stripe',
  payload_json jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_billing_subscription_events_stripe_event_id
  ON public.billing_subscription_events (stripe_event_id);
CREATE INDEX IF NOT EXISTS idx_billing_subscription_events_created_at
  ON public.billing_subscription_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_billing_subscription_events_user_id
  ON public.billing_subscription_events (user_id, created_at DESC);
